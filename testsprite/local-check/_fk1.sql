SELECT CONCAT(TABLE_NAME,'|',COLUMN_NAME,'|',REFERENCED_TABLE_NAME,'|',REFERENCED_COLUMN_NAME)
FROM information_schema.KEY_COLUMN_USAGE
WHERE TABLE_SCHEMA='academic_warning_system' AND REFERENCED_TABLE_NAME IS NOT NULL
ORDER BY TABLE_NAME, COLUMN_NAME;
SELECT '---COUNT---', COUNT(*) FROM information_schema.KEY_COLUMN_USAGE
WHERE TABLE_SCHEMA='academic_warning_system' AND REFERENCED_TABLE_NAME IS NOT NULL;
