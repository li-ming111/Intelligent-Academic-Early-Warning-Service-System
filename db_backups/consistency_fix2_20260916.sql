-- 目标库：academic_warning_system
--
-- 第一批（consistency_fix_20260916.sql）修的是**派生字段**：grade / grade_point /
-- year / enrollment_year / score_level，让它们等于系统公式算出来的值。
--
-- 这一批修的是**文字里写死的数字与结论**。它们同样是"答不上来"的来源：
--   * notifications 说司明"5 门不及格"，还把计算机基础列了两遍（47 分、59 分）；
--     帮扶计划说"四门挂科课程"里含大学英语，而大学英语实际 63 分（及格）。
--   * 李爽/张健的通知说"3 门不及格"却列出 66/69/68、64/62/65 —— 那些分数**全部 ≥60**，
--     文字与它自己给的数字直接矛盾。
--   * 辅导员汇总通知说"3 名学生：韩坤(中度)、李爽(高度)、张健(高度)"，
--     而规则表算出来是 韩坤低级(1级)、李爽/张健中级(2级)，且**漏了同班的司明**。
--   * courses.type 混用 4 种词汇（必修 / 必修课 / 选修课 / 选修），
--     而 AdminCourses.vue:42 是用 '必修课' 做全等比较来定标签样式的。
--
-- 原则同第一批：**只写能由权威数据唯一确定的文字**。每个人挂几门、哪几门、
-- 各多少分、什么等级，都由 scores + warning_rules 唯一决定，不含任何猜测。
--
-- 可回滚：全程事务；执行前快照见 academic_warning_system_pre_fix2_20260916.sql。
-- ========================================

START TRANSACTION;

-- ---------------------------------------------------------------
-- 1) notifications：按权威口径重写正文与标题
--    权威口径 = 每门课取「期末已录入」的最新一次，<60 才算挂科，按课程去重。
--    等级 = warning_rules 里 fail_count 区间命中的那条规则的 level。
--
--    收件人对照（已核实）：
--      id=1    user 39 = 韩坤(学号 2023020607)  2 门 → RULE001 → 1 级 低级
--      id=2    user 46 = 李爽(学号 2023020510)  3 门 → RULE002 → 2 级 中级
--      id=3    user 52 = 张健(学号 2023020524)  3 门 → RULE002 → 2 级 中级
--      id=4    user 53 = 辅导员(负责计科2306班)
--      id=1001 user 27 = 司明(学号 2023020616)  3 门 → RULE002 → 2 级 中级
--      id=1002 司明，帮扶计划通知，正文无数字，不动
-- ---------------------------------------------------------------

UPDATE notifications SET title = '低级预警通知',
       content = '韩坤同学，您的成绩单中有2门课程不及格（操作系统54分、数据结构59分），已触发低级预警。请尽快与辅导员联系。'
WHERE id = 1;

UPDATE notifications SET title = '中级预警通知',
       content = '李爽同学，您的成绩单中有3门课程不及格（计算机网络47分、计算机基础52分、高等数学54分），已触发中级预警。请务必重视并尽快联系辅导员。'
WHERE id = 2;

UPDATE notifications SET title = '中级预警通知',
       content = '张健同学，您的成绩单中有3门课程不及格（计算机基础48分、计算机网络49分、高等数学52分），已触发中级预警。建议及时寻求学业帮扶。'
WHERE id = 3;

-- 4 名学生全部在计科2306班（已核实 class_id 均为 1），原通知漏了司明。
UPDATE notifications SET title = '班级预警汇总',
       content = '您负责的计科2306班中，有4名学生触发了学业预警：司明(中级)、韩坤(低级)、李爽(中级)、张健(中级)。请及时跟进帮扶。'
WHERE id = 4;

-- 原正文把「计算机基础」的两个学期（sem4 59分、sem5 47分）当成两门课，
-- 于是数出 5 门。按课程去重取最新后是 3 门：操作系统40、计算机基础47、高等数学56.5。
UPDATE notifications SET title = '中级预警通知',
       content = '司明同学，您的成绩单中有3门课程不及格（操作系统40分、计算机基础47分、高等数学56.5分），已触发中级预警。请尽快联系辅导员沟通帮扶安排。'
WHERE id = 1001;

-- 1.1) warning_id 清理
--      id=1/2/3 的 warning_id 是 1/2/3，但 academic_warning 里从来没有过这些行
--      （现存那条遗留数据的 id 是 301/302/303，已归档到 _bak_ 表）→ 纯悬空引用。
--      id=1001 的 301 指向归档表里的真实行，保留以记录来龙去脉。
--      置 NULL 的含义是"未关联预警"，比指向一行不存在的记录诚实。
UPDATE notifications SET warning_id = NULL WHERE id IN (1, 2, 3);

-- ---------------------------------------------------------------
-- 2) assistance_plans：把"补习哪几门"改成真实的挂科课程
--    只改点名了点错课程的两条；id=1(韩坤，数据结构确为其挂科课) 与
--    id=3(张健，原文是"数学和编程基础"泛指) 本来就不矛盾，不动。
-- ---------------------------------------------------------------

-- 李爽的真实挂科：计算机网络47、计算机基础52、高等数学54。
-- 原文写的是"高等数学和线性代数基础"——线性代数不是本系统的课程。
UPDATE assistance_plans
SET content = '针对李爽同学的学业帮扶计划：1.重点补习计算机网络、计算机基础和高等数学基础；2.安排学伴互助；3.每两周向辅导员汇报进度；4.已安排补考'
WHERE id = 2;

-- 司明的真实挂科是 3 门（操作系统、计算机基础、高等数学）。原文写"四门"并把
-- 大学英语（实际 63 分，及格）算了进去。
UPDATE assistance_plans
SET content = '针对司明同学的学业帮扶计划：1.重点补习操作系统、计算机基础和高等数学三门挂科课程；2.安排学习小组每周两次辅导答疑；3.每两周检查一次学习进度并反馈辅导员；4.目标：本学期末补考全部通过。'
WHERE id = 1001;

-- ---------------------------------------------------------------
-- 3) courses.type：统一为「必修课 / 选修课」
--    依据：AdminCourses.vue:42 用 row.courseType === '必修课' 做全等比较决定标签样式；
--    编辑弹窗(:15-16,:99-100)也只提供这两个取值。写成「必修」「选修」的行会被
--    渲染成错误标签，且一旦在界面上保存就被静默改写成「必修课」——
--    即"存进去的值和界面认的值不是一套"。
--    这是把数据对齐到界面已认可的取值，不是新造一套词汇。
-- ---------------------------------------------------------------

UPDATE courses SET type = '必修课' WHERE type = '必修';
UPDATE courses SET type = '选修课' WHERE type = '选修';

COMMIT;

